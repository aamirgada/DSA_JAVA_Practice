package Basic_Of_Java;

public class RelationalOperators {
    static void main(String[] args) {
        int x = 5;
        int y = 9;

        System.out.println(x>y);
        System.out.println(x<y);
        System.out.println(x>=y);
        System.out.println(x<=y);
        System.out.println(x==y);
        System.out.println(x!=y);

    }

}
