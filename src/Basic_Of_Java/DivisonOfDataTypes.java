package Basic_Of_Java;

public class DivisonOfDataTypes {

    static void main(String[] args) {
        double x = 5/2;// 2.0
        System.out.println(x);
        double y = 5.0/2;
        System.out.println(y);//2.5
        double z = 5/2.0;
        System.out.println(z);//2.5
        double w = 5.0/2.0;
        System.out.println(w);//2.5
    }
}
